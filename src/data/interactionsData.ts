export function getDrugById(id: string): DrugInfo | undefined {
  return DRUGS.find(d => d.id === id);
}

/**
 * جست‌وجوی دارو در دیتابیس تداخلات — هم روی نام/alias های فارسی (با نرمال‌سازی متن
 * فارسی برای مقاومت در برابر ي/ی، ك/ک، نیم‌فاصله و غیره) و هم روی نام/alias های
 * انگلیسی (case-insensitive) انجام می‌شود. هم تطابق پیشوندی و هم تطابق شامل‌بودن
 * (substring) در نظر گرفته می‌شود؛ نتایج پیشوندی اولویت بالاتری دارند.
 */
export function searchDrugs(query: string): DrugInfo[] {
  const q = query.trim();
  if (!q) return DRUGS;

  const normQ = normalizePersianText(q);
  const enQ = q.toLowerCase();

  const prefixMatches: DrugInfo[] = [];
  const containsMatches: DrugInfo[] = [];

  for (const d of DRUGS) {
    const faCandidates = [d.name, ...(d.aliases ?? [])].map(normalizePersianText);
    const enCandidates = [d.en, ...(d.enAliases ?? [])]
      .filter((v): v is string => Boolean(v))
      .map(v => v.toLowerCase());

    const isPrefix =
      faCandidates.some(c => c.startsWith(normQ)) ||
      enCandidates.some(c => c.startsWith(enQ));
    const isContains =
      faCandidates.some(c => c.includes(normQ)) ||
      enCandidates.some(c => c.includes(enQ));

    if (isPrefix) {
      prefixMatches.push(d);
    } else if (isContains) {
      containsMatches.push(d);
    }
  }

  return [...prefixMatches, ...containsMatches];
}

export interface DrugInteractionResult {
  id: string;
  kind: 'drug' | 'food';
  label: string; // نام داروی مقابل یا غذا/نوشیدنی
  category?: string; // دسته دارویی طرف مقابل (فقط برای kind === 'drug')
  severity: InteractionSeverity;
  summary: string;
  description: string;
  advice: string;
}

/** همه تداخلات شناخته‌شده (دارو و غذا) برای یک داروی مشخص را برمی‌گرداند. */
export function getInteractionsForDrug(drugId: string): DrugInteractionResult[] {
  const results: DrugInteractionResult[] = [];

  DRUG_DRUG_INTERACTIONS.forEach(item => {
    if (item.a === drugId || item.b === drugId) {
      const otherId = item.a === drugId ? item.b : item.a;
      const other = getDrugById(otherId);
      results.push({
        id: item.id,
        kind: 'drug',
        label: other?.name ?? otherId,
        category: other?.category,
        severity: item.severity,
        summary: item.summary,
        description: item.description,
        advice: item.advice
      });
    }
  });

  DRUG_FOOD_INTERACTIONS.forEach(item => {
    if (item.drug === drugId) {
      results.push({
        id: item.id,
        kind: 'food',
        label: item.item,
        severity: item.severity,
        summary: item.summary,
        description: item.description,
        advice: item.advice
      });
    }
  });

  // خطرناک‌ها همیشه اول نمایش داده شوند
  return results.sort((x, y) => (x.severity === y.severity ? 0 : x.severity === 'danger' ? -1 : 1));
}

